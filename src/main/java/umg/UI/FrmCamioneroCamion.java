private void cargarTabla() {
    modeloTabla.setRowCount(0);

    List<CamioneroCamion> lista = dao.listar();

    for (CamioneroCamion r : lista) {
        modeloTabla.addRow(new Object[]{
            r.getIdCamioneroCamion(),
            r.getNombreCamionero(),
            r.getNoPlaca(),
            r.getIdCamionero(),
            r.getIdCamion()
        });
    }
}

