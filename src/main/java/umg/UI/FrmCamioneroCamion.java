    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        if (!validarCampos()) {
    return;
}

CamioneroCamion r = new CamioneroCamion();
r.setIdCamionero(
    Integer.parseInt(txtCamionero.getText().trim()));
r.setIdCamion(
    Integer.parseInt(txtCamion.getText().trim()));

if (dao.insertar(r)) {
    JOptionPane.showMessageDialog(this,
        "Asignacion registrada correctamente.");
    cargarTabla();
    limpiarCampos();
}
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        if (txtIDAsignacion.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this,
        "Selecciona una asignacion de la tabla.");
    return;
}

if (!validarCampos()) {
    return;
}

try {
    CamioneroCamion r = new CamioneroCamion();

    r.setIdCamioneroCamion(
        Integer.parseInt(txtIDAsignacion.getText().trim()));
    r.setIdCamionero(
        Integer.parseInt(txtCamionero.getText().trim()));
    r.setIdCamion(
        Integer.parseInt(txtCamion.getText().trim()));

    if (dao.actualizar(r)) {
        JOptionPane.showMessageDialog(this,
            "Asignacion actualizada correctamente.");
        cargarTabla();
        limpiarCampos();
    }
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
        "El ID de asignacion no es valido.");
}
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (txtIDAsignacion.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this,
        "Selecciona una asignacion de la tabla.");
    return;
}

int confirmacion = JOptionPane.showConfirmDialog(
    this,
    "¿Deseas eliminar esta asignacion?",
    "Confirmar eliminacion",
    JOptionPane.YES_NO_OPTION
);

if (confirmacion != JOptionPane.YES_OPTION) {
    return;
}

try {
    int id = Integer.parseInt(
        txtIDAsignacion.getText().trim());

    if (dao.eliminar(id)) {
        JOptionPane.showMessageDialog(this,
            "Asignacion eliminada correctamente.");
        cargarTabla();
        limpiarCampos();
    }
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
        "El ID de asignacion no es valido.");
}
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblCamioneroCamionMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCamioneroCamionMouseClicked
        // TODO add your handling code here:
    int fila = tblCamioneroCamion.getSelectedRow();

    if (fila >= 0) {
        txtIDAsignacion.setText(
            modeloTabla.getValueAt(fila, 0).toString());

        txtCamionero.setText(
            modeloTabla.getValueAt(fila, 3).toString());

        txtCamion.setText(
            modeloTabla.getValueAt(fila, 4).toString());
    }

    // La tabla muestra el nombre y la placa, no los IDs.
    // Por eso aquí solo se selecciona la asignación.
    }//GEN-LAST:event_tblCamioneroCamionMouseClicked

