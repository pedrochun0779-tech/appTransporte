     private void configurarTabla() {
        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{"ID", "Nombre"}, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        tblCiudad.setModel(modelo);
        tblCiudad.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);

        tblCiudad.getSelectionModel().addListSelectionListener(evento -> {
            if (!evento.getValueIsAdjusting()) {
                int filaVista = tblCiudad.getSelectedRow();
                if (filaVista >= 0) {
                    int fila = tblCiudad.convertRowIndexToModel(filaVista);
                    txtID.setText(String.valueOf(tblCiudad.getModel().getValueAt(fila, 0)));
                    txtNombre.setText(String.valueOf(tblCiudad.getModel().getValueAt(fila, 1)));
                }
            }
        });
    }

    private void cargarCiudades() {
        DefaultTableModel modelo = (DefaultTableModel) tblCiudad.getModel();
        modelo.setRowCount(0);
        try {
            List<Ciudad> ciudades = ciudadDAO.listar();
            for (Ciudad ciudad : ciudades) {
                modelo.addRow(new Object[]{ciudad.getIdCiudad(), ciudad.getNombre()});
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "No se pudieron cargar las ciudades:\n" + e.getMessage(),
                    "Error de consulta", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limpiarCampos() {
        txtID.setText("");
        txtNombre.setText("");
        tblCiudad.clearSelection();
        txtNombre.requestFocusInWindow();
    }

    private boolean validarNombre() {
        if (txtNombre.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el nombre de la ciudad.",
                    "Dato obligatorio", JOptionPane.WARNING_MESSAGE);
            txtNombre.requestFocusInWindow();
            return false;
        }
        return true;
    }

    private Integer obtenerId() {
        String textoId = txtID.getText().trim();
        if (textoId.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione una ciudad de la tabla para continuar.",
                    "ID requerido", JOptionPane.WARNING_MESSAGE);
            return null;
        }
        try {
            int id = Integer.parseInt(textoId);
            if (id <= 0) {
                JOptionPane.showMessageDialog(this, "El ID debe ser mayor que cero.");
                return null;
            }
            return id;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID debe ser un número entero.");
            return null;
        }
    }


