    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
       if (!validarNombre()) return;
        try {
            Ciudad ciudad = new Ciudad();
            ciudad.setNombre(txtNombre.getText().trim());
            ciudadDAO.insertar(ciudad);
            JOptionPane.showMessageDialog(this, "Ciudad guardada correctamente.");
            cargarCiudades();
            limpiarCampos();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
 
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
       Integer id = obtenerId();
        if (id == null || !validarNombre()) return;

        int opcion = JOptionPane.showConfirmDialog(this,
                "¿Desea actualizar la ciudad con ID " + id + "?",
                "Confirmar actualización", JOptionPane.YES_NO_OPTION);
        if (opcion != JOptionPane.YES_OPTION) return;

        try {
            Ciudad ciudad = new Ciudad(id, txtNombre.getText().trim());
            ciudadDAO.actualizar(ciudad);
            JOptionPane.showMessageDialog(this, "Ciudad actualizada correctamente.");
            cargarCiudades();
            limpiarCampos();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
  
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        Integer id = obtenerId();
        if (id == null) return;

        int opcion = JOptionPane.showConfirmDialog(this,
                "¿Está seguro de eliminar la ciudad con ID " + id + "?",
                "Confirmar eliminación", JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);
        if (opcion != JOptionPane.YES_OPTION) return;

        try {
            ciudadDAO.eliminar(id);
            JOptionPane.showMessageDialog(this, "Ciudad eliminada correctamente.");
            cargarCiudades();
            limpiarCampos();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnEliminarActionPerformed

