    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        try {
        String placa = txtNoPlaca.getText().trim();
        String modelo = txtModelo.getText().trim();
        String tipo = txtTipo.getText().trim();
        String potencia = txtPotencia.getText().trim();

        if (placa.isEmpty() || modelo.isEmpty()
                || tipo.isEmpty() || potencia.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Completa todos los campos."
            );
            return;
        }

        umg.modelo.Camion camion = new umg.modelo.Camion(
            0, placa, modelo, tipo, potencia
        );

        if (camionDAO.insertar(camion)) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Camión guardado correctamente."
            );
            cargarCamiones();
            limpiarCampos();
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Error al guardar: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
      try {
        String placa = txtNoPlaca.getText().trim();
        String modelo = txtModelo.getText().trim();
        String tipo = txtTipo.getText().trim();
        String potencia = txtPotencia.getText().trim();

        if (placa.isEmpty() || modelo.isEmpty()
                || tipo.isEmpty() || potencia.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Completa todos los campos.");
            return;
        }

        umg.modelo.Camion camion =
                new umg.modelo.Camion(
                        0, placa, modelo, tipo, potencia);

        boolean guardado = camionDAO.insertar(camion);

        if (guardado) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Camión guardado correctamente.");

            cargarCamiones();
            limpiarCampos();
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "No se pudo guardar el camión:\n" + e.getMessage(),
                "Error al guardar",
                javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        try {
        if (txtIDCamion.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Selecciona un camión para eliminar."
            );
            return;
        }

        int id = Integer.parseInt(txtIDCamion.getText().trim());

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Deseas eliminar el camión con ID " + id + "?",
            "Confirmar eliminación",
            javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirmacion != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        if (camionDAO.eliminar(id)) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Camión eliminado correctamente."
            );
            cargarCamiones();
            limpiarCampos();
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this, "No existe un camión con ese ID."
            );
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "El ID debe ser un número entero."
        );
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Error al eliminar: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_btnEliminarActionPerformed
   private void limpiarCampos() {
    txtIDCamion.setText("");
    txtNoPlaca.setText("");
    txtModelo.setText("");
    txtTipo.setText("");
    txtPotencia.setText("");
    tblCamion.clearSelection();
    txtNoPlaca.requestFocus();
}
